const STORAGE_KEY = 'lactaflow_dairy_records_v1';

export function loadStoredRecords(): BaseRecord[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      // First run: save and return initial seeds
      const initial = [
        ...INITIAL_INTAKE_RECORDS,
        ...INITIAL_QUALITY_RECORDS,
        ...INITIAL_LOGISTICS_RECORDS,
      ];
      localStorage.setItem(STORAGE_KEY, JSON.stringify(initial));
      return initial;
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
    return [
      ...INITIAL_INTAKE_RECORDS,
      ...INITIAL_QUALITY_RECORDS,
      ...INITIAL_LOGISTICS_RECORDS,
    ];
  } catch (err) {
    console.error('Failed to read from localStorage:', err);
    return [
      ...INITIAL_INTAKE_RECORDS,
      ...INITIAL_QUALITY_RECORDS,
      ...INITIAL_LOGISTICS_RECORDS,
    ];
  }
}

export function saveStoredRecords(records: BaseRecord[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(records));
  } catch (err) {
    console.error('Failed to save records to localStorage:', err);
  }
}

export function resetToSeedData(): BaseRecord[] {
  const initial = [
    ...INITIAL_INTAKE_RECORDS,
    ...INITIAL_QUALITY_RECORDS,
    ...INITIAL_LOGISTICS_RECORDS,
  ];
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(initial));
  } catch (err) {
    console.error('Failed to reset localStorage:', err);
  }
  return initial;
}
