"""Writes installer/Files.wxs: one component per file in the PyInstaller output folder (T9.4).

Run after every PyInstaller build, before `wix build`. The component GUIDs are kept in
installer/component_guids.json, so an upgrade replaces the same components.
"""

import json
import sys
import uuid
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

HERE = Path(__file__).resolve().parent
# build.ps1 passes the folder PyInstaller wrote for this version; run alone, it uses dist\ExpenseLedger.
SOURCE = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else HERE.parent / "dist" / "ExpenseLedger"
GUID_FILE = HERE / "component_guids.json"
OUTPUT = HERE / "Files.wxs"


def load_guids() -> dict[str, str]:
    if GUID_FILE.exists():
        return json.loads(GUID_FILE.read_text(encoding="utf-8"))
    return {}


def main() -> None:
    guids = load_guids()
    counter = {"dir": 0, "file": 0}
    lines: list[str] = []
    component_ids: list[str] = []

    def guid_for(key: str) -> str:
        if key not in guids:
            guids[key] = "{" + str(uuid.uuid4()).upper() + "}"
        return guids[key]

    def write_folder(folder: Path, indent: int) -> None:
        pad = "  " * indent
        for entry in sorted(folder.iterdir(), key=lambda p: (p.is_file(), p.name.lower())):
            relative = entry.relative_to(SOURCE).as_posix()
            if entry.is_dir():
                counter["dir"] += 1
                lines.append(f"{pad}<Directory Id={quoteattr('d' + str(counter['dir']))} Name={quoteattr(entry.name)}>")
                write_folder(entry, indent + 1)
                lines.append(f"{pad}</Directory>")
            else:
                counter["file"] += 1
                number = counter["file"]
                component_id = f"c{number}"
                component_ids.append(component_id)
                lines.append(f"{pad}<Component Id={quoteattr(component_id)} Guid={quoteattr(guid_for(relative))}>")
                lines.append(f"{pad}  <File Id={quoteattr('f' + str(number))} Source={quoteattr(str(entry))} KeyPath=\"yes\" />")
                lines.append(f"{pad}</Component>")

    write_folder(SOURCE, 3)
    body = "\n".join(lines)
    refs = "\n".join(f'      <ComponentRef Id={quoteattr(cid)} />' for cid in component_ids)
    document = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by generate_files.py. Do not edit by hand. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Fragment>
    <DirectoryRef Id="APPLICATIONFOLDER">
{body}
    </DirectoryRef>
  </Fragment>
  <Fragment>
    <ComponentGroup Id="ProgramFilesGroup">
{refs}
    </ComponentGroup>
  </Fragment>
</Wix>
"""
    OUTPUT.write_text(document, encoding="utf-8")
    GUID_FILE.write_text(json.dumps(guids, indent=2), encoding="utf-8")
    print(f"wrote {OUTPUT.name}: {counter['file']} files, {counter['dir']} folders")


if __name__ == "__main__":
    main()
